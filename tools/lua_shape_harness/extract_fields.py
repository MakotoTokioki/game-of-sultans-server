#!/usr/bin/env python3
"""Statically extract response fields read by a client action callback.

Pure text analysis of the decompiled Lua — no Lua runtime needed, so it works
even for modules that fail to load in the sandbox. For a given action id we
find the request function `actionNNNNN`, locate the callback it passes to
`netProtocol.action(NNNNN, ...)`, and list every field read from the response
parameter (A0_3, A0_2 inside the callback) — i.e. the minimal response shape.

Usage:
  python3 tools/lua_shape_harness/extract_fields.py 11302
  python3 tools/lua_shape_harness/extract_fields.py --all   # recon/protocol/static-fields.md
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

SERVER = Path(__file__).resolve().parents[2]
DECOMP = Path("/tmp/opencode/gos/decomp_all")
RECON = SERVER.parent / "recon" / "protocol"

_FIELD = re.compile(r"\bA(\d)_(\d)\.([A-Za-z_]\w*)")


def find_module(action: str) -> Path | None:
    for base in ("modules", "scene"):
        for p in sorted((DECOMP / base).rglob("*.lua")):
            try:
                s = p.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                continue
            if re.search(rf"\baction{action}\s*=", s) or re.search(rf"\b{action}\b", s):
                return p
    return None


def extract(action: str) -> dict:
    mod = find_module(action)
    if not mod:
        return {"action": action, "module": None, "fields": [], "status": "NO_MODULE"}
    lines = mod.read_text(encoding="utf-8", errors="ignore").splitlines()

    # find the request function: `actionNNNNN = Lxx` then the following `function Lxx(...)`
    req_name = None
    assign_i = None
    for i, ln in enumerate(lines):
        m = re.search(rf"\baction{action}\s*=\s*(L\d+_\d+)", ln)
        if m:
            req_name = m.group(1)
            assign_i = i
            break
    if req_name is None:
        return {"action": action, "module": mod.name, "fields": [], "status": "NO_REQ_FN"}
    # decompiler reuses local names: the function assigned here is the most
    # recent `function <name>(` defined BEFORE the assignment line.
    start = None
    for j in range(assign_i - 1, -1, -1):
        if re.search(rf"function\s+{re.escape(req_name)}\s*\(", lines[j]):
            start = j
            break
    if start is None:
        return {"action": action, "module": mod.name, "fields": [], "status": "NO_REQ_FN"}

    # walk block depth to find the matching `end` of the request function
    opener = re.compile(r"^(function|if|for|while|repeat|do)\b")
    depth = 0
    end = len(lines)
    for j in range(start, len(lines)):
        t = lines[j].strip()
        if opener.match(t):
            depth += 1
        elif t == "end" or t.startswith("end "):
            depth -= 1
            if depth == 0:
                end = j + 1
                break
    region = "\n".join(lines[start:end])

    # the response callback is a nested `function Lxx(A0_N)` in this region.
    # It is the LAST such nested function (the one passed to netProtocol.action).
    cb_var = None
    for m in re.finditer(r"function\s+L\d+_\d+\s*\(\s*(A\d_\d)\s*\)", region):
        cb_var = m.group(1)
    if not cb_var:
        cb_var = "A0_3"

    fields = sorted(set(
        m.group(3) for m in _FIELD.finditer(region)
        if f"A{m.group(1)}_{m.group(2)}" == cb_var
    ))
    return {
        "action": action,
        "module": mod.name,
        "status": "OK",
        "response_param": cb_var,
        "fields": fields,
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("action", nargs="?")
    ap.add_argument("--all", action="store_true")
    a = ap.parse_args()
    if a.all:
        from run import build_action_index
        idx = build_action_index()
        rows = [extract(x) for x in sorted(idx)]
        RECON.mkdir(parents=True, exist_ok=True)
        out = RECON / "static-fields.md"
        lines = ["# Statically extracted response fields", "",
                 "Generated by `extract_fields.py --all`. Lists fields read by each",
                 "client action callback (the minimal response shape).", "",
                 "| Action | Module | Status | Response param | Fields |",
                 "|---|---|---|---|---|"]
        for r in rows:
            lines.append(f"| {r['action']} | {r.get('module') or '-'} | {r['status']} | "
                         f"{r.get('response_param', '-')} | {', '.join(r['fields'])[:300]} |")
        out.write_text("\n".join(lines) + "\n")
        print(f"wrote {out} — {len(rows)} actions")
    elif a.action:
        import json
        print(json.dumps(extract(a.action), indent=2))
    else:
        ap.print_help()


if __name__ == "__main__":
    main()
